export const loadRoleplayCases = () => roleplayCases;

export const getRoleplayCasesByRole = (role: Role) =>
  roleplayCases.filter((c) => c.role === role);

export const getRandomRoleplayCase = (role?: Role | null) => {
  const pool = role ? getRoleplayCasesByRole(role) : roleplayCases;
  if (pool.length === 0) return null;
  return pool[Math.floor(Math.random() * pool.length)];
};

export const getAllRoleplayDiagnoses = (): string[] => {
  const set = new Set<string>();
  roleplayCases.forEach((c) => c.diagnosis.forEach((d) => set.add(d)));
  return Array.from(set).sort((a, b) => a.localeCompare(b, 'ru'));
};
